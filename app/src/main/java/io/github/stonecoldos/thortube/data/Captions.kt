package io.github.stonecoldos.thortube.data

import io.github.stonecoldos.thortube.AppLog
import io.github.stonecoldos.thortube.ThorTubeApp
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.Request
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.StreamInfo

/** A caption language a video offers. [auto] = YouTube's speech-to-text captions. */
data class CaptionTrack(val lang: String, val label: String, val auto: Boolean, val url: String)

/** One caption on screen from [startMs] to [endMs]. */
data class Cue(val startMs: Long, val endMs: Long, val text: String)

/**
 * Captions are fetched and drawn by the app itself (not the video player), so switching
 * language is instant and they show over the CRT effect too.
 */
object Captions {

    fun tracks(info: StreamInfo): List<CaptionTrack> = info.subtitles
        .filter { it.isUrl && it.format == MediaFormat.VTT }
        .map {
            val name = it.displayLanguageName?.takeIf { n -> n.isNotBlank() } ?: it.languageTag
            CaptionTrack(it.languageTag, if (it.isAutoGenerated) "$name (auto)" else name, it.isAutoGenerated, it.content)
        }
        .distinctBy { it.lang to it.auto }
        .sortedWith(compareBy<CaptionTrack> { it.auto }.thenBy { it.label })

    /** The track to use for someone who last chose [lang]: their own language, real captions first. */
    fun pick(tracks: List<CaptionTrack>, lang: String): CaptionTrack? {
        val base = lang.substringBefore('-')
        return tracks.firstOrNull { !it.auto && it.lang == lang }
            ?: tracks.firstOrNull { !it.auto && it.lang.substringBefore('-') == base }
            ?: tracks.firstOrNull { it.auto && it.lang.substringBefore('-') == base }
    }

    suspend fun load(track: CaptionTrack): List<Cue> = withContext(Dispatchers.IO) {
        runCatching {
            ThorTubeApp.http.newCall(Request.Builder().url(track.url).build()).execute().use { r ->
                if (!r.isSuccessful) error("HTTP ${r.code}")
                parse(r.body!!.string())
            }
        }.onFailure { AppLog.w("ThorTube", "Captions failed for ${track.lang}", it) }
            .getOrDefault(emptyList())
            .also { AppLog.d("ThorTube", "Captions ${track.label}: ${it.size} cues") }
    }

    /** The text to show at [ms], or "" if nothing. [cues] must be sorted by start time. */
    fun at(cues: List<Cue>, ms: Long): String {
        if (cues.isEmpty()) return ""
        // Last cue starting at or before ms, then gather the overlapping ones around it.
        var lo = 0
        var hi = cues.size - 1
        var idx = -1
        while (lo <= hi) {
            val mid = (lo + hi) / 2
            if (cues[mid].startMs <= ms) { idx = mid; lo = mid + 1 } else hi = mid - 1
        }
        if (idx < 0) return ""
        val lines = mutableListOf<String>()
        var i = idx
        while (i >= 0 && idx - i < 4) {
            val c = cues[i]
            if (c.endMs > ms) lines.add(0, c.text)
            i--
        }
        return lines.joinToString("\n").lines().filter { it.isNotBlank() }.distinct().takeLast(2).joinToString("\n")
    }

    private val time = Regex("""(?:(\d+):)?(\d{1,2}):(\d{2})[.,](\d{3})""")
    private val tag = Regex("<[^>]*>")

    internal fun parse(vtt: String): List<Cue> {
        val out = mutableListOf<Cue>()
        for (block in vtt.replace("\r", "").split(Regex("\n\\s*\n"))) {
            val lines = block.lines()
            val at = lines.indexOfFirst { "-->" in it }
            if (at < 0) continue
            val (a, b) = lines[at].split("-->").map { it.trim() }
            val start = ms(a) ?: continue
            val end = ms(b) ?: continue
            if (end - start < 50) continue   // YouTube's auto captions pad with 10 ms repeat cues
            val text = lines.drop(at + 1)
                .map { tag.replace(it, "").replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">").replace("&nbsp;", " ").replace("&#39;", "'").replace("&quot;", "\"").trim() }
                .filter { it.isNotEmpty() }
                .joinToString("\n")
            if (text.isNotEmpty()) out += Cue(start, end, text)
        }
        return out.sortedBy { it.startMs }
    }

    private fun ms(s: String): Long? {
        val m = time.find(s) ?: return null
        val (h, mi, se, mil) = m.destructured
        return ((h.ifEmpty { "0" }.toLong() * 60 + mi.toLong()) * 60 + se.toLong()) * 1000 + mil.toLong()
    }
}
